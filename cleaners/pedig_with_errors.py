"""Compare optiSel::prePed and pedsum validate on optiSel::PedigWithErrors.

Reads the export written by pedig_with_errors.R, runs ``pedsum validate`` on
it under each mode of run_pedsum.py, and writes
cleaners/results/PedigWithErrors.md: per program, the rows in and out, the
rows added and removed, the parent links cleared or changed, the sexes
changed, and the founder and half-founder counts of the result.

Parents are compared as written: the input's one father written ``0`` counts
as a cleared link where a program read it as missing (prePed), and as a kept
link to an added founder named ``0`` where it did not (pedsum).

Run: pixi run cleaners-pwe (after pixi run -e r cleaners-pwe-r)
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from compare import has_cycle, load_ped
from run_pedsum import MODES, validate

if TYPE_CHECKING:
    from compare import Ped

HERE = Path(__file__).parent

# PedigWithErrors has a father written 0 with no row and two cycles, so each mode of run_pedsum.py
# BLOCKs on one or the other; these combine the ADR 0006 options that clear both.
COMBINED: dict[str, list[str]] = {
    "token-0-drop": ["--missing-parent-token", "0", "--drop-offending"],
    "token-0-break-cycles": ["--missing-parent-token", "0", "--break-cycles"],
    "token-0-break-cycles-drop": ["--missing-parent-token", "0", "--break-cycles", "--drop-offending"],
}
WORK = HERE.parent / ".work" / "cleaners" / "PedigWithErrors"


def counts(inp: Ped, out: Ped) -> dict[str, object]:
    """Size and repair counts of ``out``, diffed against ``inp``."""
    kept = [i for i in inp if i in out]
    cleared = changed = 0
    for i in kept:
        for k in (0, 1):
            before, after = inp[i][k], out[i][k]
            if before != after:
                if after == "NA":
                    cleared += 1
                else:
                    changed += 1
    founders = sum(1 for m, f, _ in out.values() if m == "NA" and f == "NA")
    half = sum(1 for m, f, _ in out.values() if (m == "NA") != (f == "NA"))
    return {
        "rows out": len(out),
        "added": sum(1 for i in out if i not in inp),
        "removed": sum(1 for i in inp if i not in out),
        "parent links cleared": cleared,
        "parent links changed": changed,
        "sex changed": sum(1 for i in kept if inp[i][2] != out[i][2]),
        "founders": founders,
        "half-founders": half,
        "cycle left": has_cycle(out),
    }


def main() -> None:
    """Run pedsum on the export and write results/PedigWithErrors.md."""
    inp, _ = load_ped(WORK / "input.tsv")
    rows: dict[str, dict[str, object]] = {"input": counts(inp, inp)}
    notes: dict[str, str] = {"optiSel-prePed": (WORK / "prePed.messages.txt").read_text().strip()}
    out, _ = load_ped(WORK / "prePed.tsv")
    rows["optiSel-prePed"] = counts(inp, out)

    for mode, flags in {**MODES, **COMBINED}.items():
        name = f"pedsum-{mode}"
        record, ped_rows = validate(WORK / "input.tsv", WORK / name, flags)
        notes[name] = f"{record['outcome']}; failed: {record['failed_checks'] or 'none'}"
        if record["blocked"]:
            notes[name] += f"; BLOCKED: {record['blocked']}"
        if record["outcome"] in ("blocked", "error"):
            continue
        rows[name] = counts(inp, {r["id"]: (r["mother"], r["father"], r["sex"]) for r in ped_rows})

    keys = list(rows["input"])
    lines = [
        "# optiSel::PedigWithErrors: prePed vs pedsum validate",
        "",
        "Generated by `cleaners/pedig_with_errors.py`. `input` is the dataset as shipped "
        "(optiSel 2.1.0); every other row is a program's cleaned pedigree diffed against it.",
        "",
        "| program | " + " | ".join(keys) + " |",
        "|---|" + "---|" * len(keys),
    ]
    lines += [f"| {p} | " + " | ".join(str(c[k]) for k in keys) + " |" for p, c in rows.items()]
    lines += ["", "## What each program said", ""]
    lines += [f"- **{p}**: {n}" for p, n in notes.items()]
    (HERE / "results" / "PedigWithErrors.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
